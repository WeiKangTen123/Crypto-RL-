"""
Regenerates .gemini/shared/KNOWLEDGE_BASE.md Section 1 (Strategy Registry)
from scan_results.json + settings.py.

Run manually or by @crypto-fullstack during Stage [4/4] FINALIZE.
Preserves Sections 2 and 3 (Factor Intelligence, Operational Mandates).
"""

import json
import os
import re
from datetime import datetime

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))))

SCAN_RESULTS = os.path.join(ROOT, '.gemini', 'skills', 'crypto-strategy-tuner', 'data', 'scan_results.json')
SETTINGS_PY  = os.path.join(ROOT, 'strategy_backtest', 'settings.py')
KB_PATH      = os.path.join(ROOT, '.gemini', 'shared', 'KNOWLEDGE_BASE.md')


def load_scan_grades():
    """Return {numeric_key: {grade, sharpe}} from scan_results.json."""
    with open(SCAN_RESULTS) as f:
        data = json.load(f)
    grades = {}
    results = data.get('results', [])
    for val in results:
        if isinstance(val, dict) and 'id' in val:
            grades[str(val['id'])] = {
                'grade': val.get('grade', 'PENDING'),
                'sharpe': val.get('sharpe', 0.0),
            }
    return grades


def load_settings():
    """Return list of strategy dicts from settings.py STRATEGY_LIBRARY."""
    text = open(SETTINGS_PY).read()
    # Extract numeric outer keys
    pattern = re.compile(
        r'"(\d+)"\s*:\s*\{[^}]*?"id"\s*:\s*"([^"]+)"[^}]*?"class"\s*:\s*"([^"]+)"[^}]*?"data"\s*:\s*\{[^}]*?"coins"\s*:\s*"([^"]+)"[^}]*?"timeframes"\s*:\s*"([^"]+)"',
        re.DOTALL
    )
    strategies = []
    for m in pattern.finditer(text):
        strategies.append({
            'num_key': m.group(1),
            'id': m.group(2),
            'class': m.group(3),
            'coin': m.group(4),
            'tf': m.group(5),
        })
    return strategies


def infer_factor_class(class_name):
    name = class_name.lower()
    if 'ichimoku' in name:        return 'Ichimoku'
    if 'momentum' in name:        return 'Momentum'
    if 'reversion' in name or 'mean' in name: return 'Mean Reversion'
    if 'breakout' in name:        return 'Breakout'
    if 'divergen' in name:        return 'Divergence'
    if 'funding' in name:         return 'Funding'
    if 'vwap' in name:            return 'VWAP'
    if 'volume' in name or 'fvma' in name: return 'Volume'
    if 'macd' in name:            return 'MACD'
    if 'rsi' in name or 'ema' in name:    return 'Momentum'
    if 'squeeze' in name or 'bb' in name: return 'Volatility'
    if 'smc' in name or 'order_block' in name: return 'SMC'
    if 'taker' in name:           return 'Order Flow'
    if 'trend' in name or 'tip' in name:  return 'Trend'
    return 'Other'


def build_registry_table(strategies, grades):
    rows = []
    for s in strategies:
        g = grades.get(s['num_key'], {})
        grade  = g.get('grade', 'PENDING')
        # Status: map grade to deployment stage
        status = {'GOOD': 'PAPER', 'MEDIOCRE': 'RESEARCH', 'BAD': 'BENCH', 'PENDING': 'PENDING', 'ERROR': 'ERROR'}.get(grade, 'RESEARCH')
        factor = infer_factor_class(s['class'])
        rows.append(f"| {s['num_key']} | {s['class']} | {s['coin']} | {s['tf']} | {grade} | {status} | {factor} |")
    # Sort by grade then by key
    order = {'GOOD': 0, 'MEDIOCRE': 1, 'BAD': 2, 'PENDING': 3, 'ERROR': 4}
    rows.sort(key=lambda r: (order.get(r.split('|')[5].strip(), 9), int(r.split('|')[1].strip())))
    header = "| # | Class | Coin | TF | Grade | Status | Factor Class |\n|---|---|---|---|---|---|---|"
    return header + '\n' + '\n'.join(rows)


def preserve_sections(kb_text):
    """Extract sections 2 and 3 from existing KB to preserve them."""
    sec2 = re.search(r'(## 2\..*?)(?=## 3\.|$)', kb_text, re.DOTALL)
    sec3 = re.search(r'(## 3\..*?)$', kb_text, re.DOTALL)
    return (sec2.group(1).strip() if sec2 else '## 2. Factor Intelligence (Researcher Extraction)\n_No entries yet._'),\
           (sec3.group(1).strip() if sec3 else '## 3. Operational Mandates\n_No entries yet._')


def main():
    print('Loading scan grades...')
    grades = load_scan_grades()
    print(f'  {len(grades)} graded strategies found')

    print('Loading settings.py...')
    strategies = load_settings()
    print(f'  {len(strategies)} strategies in STRATEGY_LIBRARY')

    table = build_registry_table(strategies, grades)

    existing = open(KB_PATH).read() if os.path.exists(KB_PATH) else ''
    sec2, sec3 = preserve_sections(existing)

    ts = datetime.now().strftime('%Y-%m-%d %H:%M')
    content = f"""# Crypto-RL Master Knowledge Base
> Auto-generated by `sync_knowledge_base.py` — last updated {ts}
> Grade source: `scan_results.json` | Registry source: `settings.py`

## 1. Strategy Registry (Master)
This is the canonical list of all registered strategies. Grades are set by `@crypto-strategy-tuner`.

{table}

---

{sec2}

---

{sec3}
"""
    with open(KB_PATH, 'w') as f:
        f.write(content)
    print(f'KNOWLEDGE_BASE.md updated — {len(strategies)} strategies written.')


if __name__ == '__main__':
    main()
